/** Bounding box of a province outline path, for cropping a single-province mini map. */
export function provincePathBBox(d: string): { x: number; y: number; w: number; h: number } {
  const nums = d.match(/-?\d+(?:\.\d+)?/g)?.map(Number) ?? [];
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (let i = 0; i + 1 < nums.length; i += 2) {
    const x = nums[i]!;
    const y = nums[i + 1]!;
    if (x < minX) minX = x;
    if (y < minY) minY = y;
    if (x > maxX) maxX = x;
    if (y > maxY) maxY = y;
  }
  return { x: minX, y: minY, w: maxX - minX, h: maxY - minY };
}

export function provinceName(id: LaoProvinceId, lang: string | undefined): string {
  const p = PROVINCE_BY_ID[id];
  if (!p) return id;
  return lang?.startsWith('en') ? p.nameEn : p.nameLo;
}

